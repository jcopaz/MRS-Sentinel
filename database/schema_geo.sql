-- schema_geo.sql — Geografia real da malha MRS (Sprint 6)
--
-- Tabela de REFERÊNCIA (estática) com os marcos de KM georreferenciados,
-- derivada do KMZ oficial "Marcos_KM_Malha_MRS" (2.298 marcos), agregada no
-- nível (trecho, origem, destino) — a chave mais fina que o decodificador de
-- TPLNR (core.glossarios.decodificar_tplnr) extrai de notas e do RASF.
--
-- Diferente de `notas`/`rasf_ee`, NÃO é versionada por upload: é malha física,
-- global e imutável entre releases. O app também embarca data/geo_marcos.csv
-- como fonte primária; esta tabela é a opção para quem prefere servir a
-- referência pelo Supabase (basta apontar core.geo para cá).
-- ============================================================

CREATE TABLE IF NOT EXISTS geo_marcos (
    id           BIGSERIAL PRIMARY KEY,
    trecho       VARCHAR NOT NULL,   -- ramal/trecho (SJU, LSP, LC1...)
    origem       VARCHAR NOT NULL,   -- patio de origem do segmento
    destino      VARCHAR NOT NULL,   -- patio de destino do segmento
    lat          DOUBLE PRECISION NOT NULL,
    lon          DOUBLE PRECISION NOT NULL,
    km           DOUBLE PRECISION,   -- KM real (mediana dos marcos do segmento)
    n_marcos     INT,                -- qtd de marcos agregados
    UNIQUE (trecho, origem, destino)
);

CREATE INDEX IF NOT EXISTS idx_geo_marcos_trecho ON geo_marcos(trecho);
CREATE INDEX IF NOT EXISTS idx_geo_marcos_to ON geo_marcos(trecho, origem);

COMMENT ON TABLE geo_marcos IS 'Marcos de KM georreferenciados da malha MRS (KMZ oficial), nivel (trecho,origem,destino). Sprint 6.';

ALTER TABLE geo_marcos DISABLE ROW LEVEL SECURITY;

